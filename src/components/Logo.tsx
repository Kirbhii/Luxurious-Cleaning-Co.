import logoDark from '../imports/image-3.png';
import logoLight from '../imports/logo-onlight.png';

interface LogoProps {
  /** Display height in px. Native file is 484x169 — keep at/below 64px so it stays crisp on retina screens. */
  height?: number;
  align?: 'left' | 'center';
  className?: string;
}

/**
 * The wordmark, in whichever of its two files matches the theme.
 *
 * The mark is a raster, not text: image-3.png draws "LUXURIOUS" in white and
 * "CLEANING CO." in a tan. On the dark bar that is right. On the light theme's
 * white bar the white word disappears — the gold icon survives and the words do
 * not, which reads as a broken logo rather than as a theme.
 *
 * logo-onlight.png is the same artwork with those two words rewritten to near
 * black, generated by mfa-harness/make-logo-onlight.py so it is reproducible
 * rather than a hand-edited asset. The alpha channel is untouched, so the shape
 * is identical and only the colour differs.
 *
 * BOTH files are always mounted and the theme picks one in CSS. Choosing in
 * React would mean holding the theme as state here — a second copy of an answer
 * the document already gives — and this component is used in the footer and in
 * a modal, where a re-render for a colour is not worth having. A display rule
 * cannot get out of step with the attribute it reads.
 */
export default function Logo({ height = 64, align = 'left', className = '' }: LogoProps) {
  const width = Math.round((height * 484) / 169);

  return (
    <div className={`flex items-center ${align === 'center' ? 'justify-center' : 'justify-start'} ${className}`}>
      <img
        src={logoDark}
        alt="Luxurious Cleaning Co."
        width={width}
        height={height}
        draggable={false}
        className="theme-dark-only object-contain select-none"
        style={{ height, width: 'auto', maxWidth: 320 }}
      />
      <img
        src={logoLight}
        alt="Luxurious Cleaning Co."
        width={width}
        height={height}
        draggable={false}
        className="theme-light-only object-contain select-none"
        style={{ height, width: 'auto', maxWidth: 320 }}
      />
    </div>
  );
}
